# 34. Find First and Last Position of Element in Sorted Array

# Given an array of integers nums sorted in non-decreasing order, find the starting and ending position of a given target value.

# If target is not found in the array, return [-1, -1].

# You must write an algorithm with O(log n) runtime complexity.


# Example 1:

# Input: nums = [5,7,7,8,8,10], target = 8
# Output: [3,4]
# Example 2:

# Input: nums = [5,7,7,8,8,10], target = 6
# Output: [-1,-1]
# Example 3:


# Input: nums = [], target = 0
# Output: [-1,-1]
def searchRange(nums, target):
    n = len(nums) - 1
    left, right = 0, n
    start_index = -1
    end_index = -1
    max_find_index = 0
    min_find_index = n
    # finding start_index
    while left <= right:
        mid = (left + right) // 2
        value = nums[mid]
        if target == value:
            max_find_index = max(max_find_index, mid)
            prevIndex = mid - 1
            if prevIndex < 0 or (prevIndex >= 0 and nums[prevIndex] != target):
                start_index = mid
                break
            right = mid - 1
        elif value > target:
            min_find_index = min(min_find_index, mid)
            right = mid - 1
        else:
            left = mid + 1
    # finding end_index
    if start_index != -1:
        left, right = max_find_index, min_find_index
        while left <= right:
            mid = (left + right) // 2
            value = nums[mid]
            if target == value:

                nextIndex = mid + 1
                if nextIndex > n or (nextIndex <= n and nums[nextIndex] != target):
                    end_index = mid
                    break

                left = mid + 1
            elif value > target:

                right = mid - 1
            else:
                left = mid + 1

    return [start_index, end_index]


